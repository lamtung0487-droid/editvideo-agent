import os
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageOps


def font(size, bold=False):
    configured = os.environ.get("EDITVIDEO_FONT")
    candidates = [configured] if configured else []
    candidates += ["C:/Windows/Fonts/seguisb.ttf" if bold else "C:/Windows/Fonts/segoeui.ttf",
                   "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]
    for path in candidates:
        if path and Path(path).exists():
            return ImageFont.truetype(path, size)
    raise ValueError("Không có font Unicode. Đặt EDITVIDEO_FONT tới font có dấu tiếng Việt.")


def wrap(text, face, width):
    draw = ImageDraw.Draw(Image.new("RGB", (1, 1)))
    lines, current = [], ""
    for word in text.split():
        if draw.textlength(word, font=face) > width:
            # Long tokens must never escape the safe area.
            for char in word:
                trial = current + char
                if draw.textlength(trial, font=face) > width and current:
                    lines.append(current)
                    current = char
                else:
                    current = trial
            continue
        trial = current + " " + word if current else word
        if draw.textlength(trial, font=face) > width and current:
            lines.append(current)
            current = word
        else:
            current = trial
    if current:
        lines.append(current)
    return lines


def card(path, width, height, title, text, index, total, style):
    palette = {"documentary": ((13, 24, 30), (35, 65, 68), "#b6f071"),
               "energetic": ((24, 20, 40), (65, 35, 87), "#ffbd76"),
               "calm": ((18, 31, 39), (30, 63, 75), "#88d8d1")}
    c1, c2, accent = palette[style]
    im = Image.new("RGB", (width, height))
    draw = ImageDraw.Draw(im)
    for y in range(height):
        t = y/height
        draw.line((0, y, width, y), fill=tuple(round(a+(b-a)*t) for a,b in zip(c1,c2)))
    margin = int(width*.09)
    # Quiet framing, consistent safe areas; no autogenerated factual imagery.
    draw.ellipse((width*.58, height*.1, width*1.5, height*.1+width*.9), outline="#3a5354", width=max(1,width//540))
    small = font(max(18, width//42), True)
    draw.text((margin, height*.12), "GÓC NHÌN  /  KIẾN THỨC", font=small, fill=accent)
    face = font(max(26, width//13), True)
    lines = wrap(text, face, width-2*margin)
    while len(lines)*face.size*1.38 > height*.43 and face.size > width//32:
        face = font(face.size-2, True)
        lines = wrap(text, face, width-2*margin)
    y = height*.31
    for line in lines:
        draw.text((margin, y), line, font=face, fill="#f5f5ef")
        y += face.size*1.38
    draw.rounded_rectangle((margin, height*.25, margin+width*.11, height*.25+max(3,width//160)), radius=2, fill=accent)
    bottom = height*.85
    title_lines = wrap(title, small, width-2*margin)
    draw.text((margin, bottom), title_lines[0] if title_lines else "", font=small, fill="#aec0bb")
    draw.text((margin, bottom+small.size*1.7), f"{index+1:02} / {total:02}", font=small, fill=accent)
    im.save(path)


def prepare_still(source, target, width, height, fit, fx=.5, fy=.5):
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image).convert("RGB")
        if fit == "contain":
            image.thumbnail((width, height), Image.Resampling.LANCZOS)
            output = Image.new("RGB", (width, height), "#10191b")
            output.paste(image, ((width-image.width)//2, (height-image.height)//2))
        else:
            scale = max(width/image.width, height/image.height)
            image = image.resize((round(image.width*scale), round(image.height*scale)), Image.Resampling.LANCZOS)
            x = round((image.width-width)*fx)
            y = round((image.height-height)*fy)
            output = image.crop((x,y,x+width,y+height))
        output.save(target)
